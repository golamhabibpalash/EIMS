-- ============================================================================
-- Student Certificates (Testimonial + Transfer Certificate) - SCHEMA (POSTGRESQL)
-- One table holds both certificate types as stored records with a student snapshot.
-- Drops the earlier per-type tables (if present) and creates "StudentCertificates".
-- IDEMPOTENT. FK -> "Student"."Id". Fresh DBs get this from the EF model automatically.
-- ============================================================================

DROP TABLE IF EXISTS "TransferCertificates";
DROP TABLE IF EXISTS "Testimonials";

CREATE TABLE IF NOT EXISTS "StudentCertificates" (
    "Id"                   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Type"                 integer NOT NULL,
    "StudentId"            integer NOT NULL,
    "IssueDate"            timestamp without time zone NOT NULL,
    "DeliveryDate"         timestamp without time zone NULL,
    "LeavingDate"          timestamp without time zone NULL,
    "Reason"               character varying(500) NULL,
    "ExamName"             character varying(100) NULL,
    "TotalMarks"           character varying(50) NULL,
    "Gpa"                  character varying(50) NULL,
    "Grade"                character varying(50) NULL,
    "MeritRank"            character varying(50) NULL,
    "SignatoryName"        character varying(150) NULL,
    "SignatoryDesignation" character varying(100) NULL,
    "StudentNameSnapshot"  text NULL,
    "FatherNameSnapshot"   text NULL,
    "MotherNameSnapshot"   text NULL,
    "DobSnapshot"          timestamp without time zone NOT NULL,
    "ClassNameSnapshot"    text NULL,
    "SectionNameSnapshot"  text NULL,
    "ClassRollSnapshot"    integer NOT NULL DEFAULT 0,
    "SessionNameSnapshot"  text NULL,
    "UniqueIdSnapshot"     text NULL,
    "GenderNameSnapshot"   text NULL,
    "CreatedBy"            text NULL,
    "CreatedAt"            timestamp without time zone NOT NULL,
    "EditedBy"             text NULL,
    "EditedAt"             timestamp without time zone NOT NULL,
    "MACAddress"           text NULL,
    CONSTRAINT "FK_StudentCertificates_Student" FOREIGN KEY ("StudentId")
        REFERENCES "Student"("Id") ON DELETE RESTRICT
);
CREATE INDEX IF NOT EXISTS "IX_StudentCertificates_StudentId" ON "StudentCertificates"("StudentId");
CREATE INDEX IF NOT EXISTS "IX_StudentCertificates_Type" ON "StudentCertificates"("Type");
