-- ============================================================================
-- UserNotifications table (in-app notification centre) - POSTGRESQL
-- ----------------------------------------------------------------------------
-- PostgreSQL instances are provisioned from a dump, not from EF migrations, and
-- the app uses EnsureCreatedAsync() at runtime (which does nothing on an existing
-- database). So this table must be created by hand on each existing PG instance.
-- Idempotent (safe to re-run). Identifiers are quoted to preserve EF's PascalCase.
-- ============================================================================

CREATE TABLE IF NOT EXISTS "UserNotifications"
(
    "Id"              integer GENERATED BY DEFAULT AS IDENTITY,
    "RecipientUserId" character varying(450)       NOT NULL,
    "Title"           character varying(200)       NOT NULL,
    "Message"         character varying(1000)      NOT NULL,
    "Url"             character varying(500),
    "Category"        integer                      NOT NULL DEFAULT 0,
    "IsRead"          boolean                      NOT NULL DEFAULT false,
    "ReadAt"          timestamp without time zone,
    "CreatedBy"       text,
    "CreatedAt"       timestamp without time zone  NOT NULL,
    "EditedBy"        text,
    "EditedAt"        timestamp without time zone  NOT NULL,
    "MACAddress"      text,
    CONSTRAINT "PK_UserNotifications" PRIMARY KEY ("Id")
);

-- Supports the badge's unread-count query and the per-user list.
CREATE INDEX IF NOT EXISTS "IX_UserNotifications_RecipientUserId_IsRead"
    ON "UserNotifications" ("RecipientUserId", "IsRead");
